/**
 * Stamp the build being compiled with the commit it came from.
 *
 * The package version cannot answer "which build walked this baseline?" for
 * anyone running the CLI out of a local checkout: `0.1.0` is still `0.1.0`
 * twenty-five commits later, so two graphs produced by builds that detect
 * different things record the same string (issue #41).
 *
 * The commit is resolved HERE, at build time, and compiled into `dist`. It
 * cannot be resolved at run time: an installed package has no `.git`, and one
 * unpacked inside a project that does have one would report THAT project's
 * commit — the confident lie this is meant to remove.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * What the stamp says when the build cannot honestly name a commit — a tarball
 * install, a CI publish from an export, a machine with no git. It is a value
 * rather than an omission, because "this build could not identify itself" and
 * "this graph predates build stamping" are different facts and a diff says
 * different things about them.
 */
export const UNIDENTIFIED_BUILD = 'unknown';

const PACKAGE_ROOT = fileURLToPath(new URL('../', import.meta.url));
const STAMP_PATH = fileURLToPath(new URL('../src/build-stamp.ts', import.meta.url));

function git(root, args) {
  try {
    return execFileSync('git', args, {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
  } catch {
    return null;
  }
}

/** The commit this build comes from, marked when the tree was not clean. */
export function buildStamp(root = PACKAGE_ROOT) {
  // `git rev-parse` walks UPWARD until it finds a repository, so a package
  // built while sitting inside some other project's checkout would otherwise
  // be stamped with that project's commit. Only a checkout whose top level IS
  // this package gets to name one.
  const top = git(root, ['rev-parse', '--show-toplevel'])?.trim();
  if (!top || !existsSync(top) || realpathSync(top) !== realpathSync(resolve(root))) {
    return UNIDENTIFIED_BUILD;
  }
  const head = git(root, ['rev-parse', 'HEAD'])?.trim();
  // A repository with no commits yet has a HEAD that resolves to nothing.
  if (!head || !/^[0-9a-f]{40,64}$/.test(head)) return UNIDENTIFIED_BUILD;

  const status = git(root, ['status', '--porcelain']);
  // Cannot tell clean from dirty, so cannot claim clean.
  if (status === null) return UNIDENTIFIED_BUILD;
  // Untracked files count. "Built from abc" is false if anything unexpected
  // was in the tree, and a false `-dirty` costs a reader nothing while a false
  // clean is exactly the silent mismatch this exists to end.
  return status.trim() === '' ? head.slice(0, 12) : `${head.slice(0, 12)}-dirty`;
}

export function stampSource(stamp) {
  return `/**
 * GENERATED by scripts/stamp-build.mjs before every compile — do not edit.
 *
 * Untracked on purpose (see .gitignore): a stamp that lived in git would make
 * every build dirty the very tree it is describing.
 */
export const CLICKGRAPH_BUILD = ${JSON.stringify(stamp)};
`;
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const source = stampSource(buildStamp());
  // Rewritten only when it changed, so an unchanged stamp does not keep giving
  // `staleLocalBuildFiles` a source file newer than the dist it already has.
  if (!existsSync(STAMP_PATH) || readFileSync(STAMP_PATH, 'utf8') !== source) {
    writeFileSync(STAMP_PATH, source, 'utf8');
  }
}
